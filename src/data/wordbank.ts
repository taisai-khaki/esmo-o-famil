/** catId -> normalized word -> display word */
export const BANK_INDEX: Record<string, Map<string, string>> = (() => {
  const idx: Record<string, Map<string, string>> = {};
  for (const cat of CAT_IDS) {
    const m = new Map<string, string>();
    for (const w of WORD_BANK[cat] ?? []) {
      m.set(normalizeFa(w), w);
    }
    idx[cat] = m;
  }
  return idx;
})();

/** Display words in a category that start with the given letter (and are unused). */
export function bankWordsFor(catId: string, letter: string, used: Set<string>): string[] {
  const idx = BANK_INDEX[catId];
  if (!idx) return [];
  const out: string[] = [];
  for (const [norm, display] of idx) {
    if (startsWithLetter(display, letter) && !used.has(norm)) out.push(display);
  }
  return out;
}

export function isBankWord(catId: string, normalized: string): boolean {
  return BANK_INDEX[catId]?.has(normalized) ?? false;
}

/**
 * Weighted random letter pick: letters with a rich word bank are slightly more
 * likely, and letters with too few words are skipped entirely.
 */
export function pickLetter(): string {
  const { FA_LETTERS } = require_fa_letters();
  const entries: [string, number][] = FA_LETTERS.map((l) => {
    let total = 0;
    for (const cat of CAT_IDS) {
      total += bankWordsFor(cat, l, new Set()).length;
    }
    return [l, total];
  });
  const candidates = entries.filter(([, t]) => t >= 5);
  const pool = candidates.length >= 8 ? candidates : entries;
  const weightSum = pool.reduce((s, [, w]) => s + w, 0);
  let r = Math.random() * weightSum;
  for (const [l, w] of pool) {
    r -= w;
    if (r <= 0) return l;
  }
  return pool[pool.length - 1][0];
}

